// Текст правил «Риальто» (показывается в игре)
import { CONST, COMPANIES, COMPANY_KEYS, fmt } from '../engine/data.js';

export function rulesHTML() {
  const co = COMPANY_KEYS.map((k) => `<li><b>${COMPANIES[k].name}</b> (акция ${fmt(COMPANIES[k].price)}) — ${COMPANIES[k].income.toLowerCase()}.</li>`).join('');
  return `
<p><b>Цель игры</b> — собрать самый большой капитал. Игра заканчивается, как только кто-то введёт в эксплуатацию
оговорённое число предприятий (по умолчанию 3). Капитал = наличные + номинал акций + номинал участков.</p>

<h3>Старт</h3>
<p>Каждый игрок получает ${fmt(CONST.START_CASH)} и ${CONST.NOTES_PER_PLAYER} векселя. Очерёдность определяется броском кубиков.
Фишки ходят по внешнему кругу по часовой стрелке, с клетки 35 по <span style="color:#7fb0ff">синей стрелке</span> поднимаются на внутренний круг
(он идёт против часовой), а с Налоговой инспекции по <span style="color:#ff8a80">красной стрелке</span> возвращаются на Старт.</p>

<h3>Ход</h3>
<ol>
<li>До броска можно взять кредит в банке (1 за ход) и купить страховые свидетельства.</li>
<li>Бросок двух кубиков, фишка идёт на выпавшее число клеток.</li>
<li>Действие клетки, на которой остановились. Кредиты, векселя и займы можно гасить в любой момент через «Портфель».</li>
</ol>

<h3>Предприятия</h3>
<p>Предприятие строится на своём участке. Сначала покупается <b>лицензия</b> отрасли (${fmt(CONST.LICENSE_PRICE)}), затем в любом порядке
карты <b>Материалы</b>, <b>Оборудование</b> (в Торговом доме или на «Сделке») и <b>Персонал</b> (в Кадровом центре или на «Сделке»).
Их цены — в таблице в центре поля. Когда все 4 карты собраны, банк платит выручку отрасли плюс половину цены участка, лицензия остаётся у вас
как введённое предприятие, остальные карты возвращаются в банк. На одном участке можно строить предприятия одно за другим.</p>
<p>Если у компании-продавца (Торговый дом / Кадровый центр) есть акционеры, а вы не контролируете её (2–3 акции или единственная выкупленная),
каждый акционер называет свои комиссионные. Можно согласиться, один раз попросить снизить или отказаться — тогда акционеры платят штраф
в размере запрошенного, а вы теряете остаток хода.</p>

<h3>Клетки</h3>
<ul>
<li><b>Сделка</b> — одна из сделок: купить/продать акцию, купить лицензию, купить Материалы/Оборудование/Персонал, продать участок.</li>
<li><b>Участок</b> — свободный можно купить по цене на клетке, иначе он уходит на аукцион. Если никто не купит, отказавшийся платит 20%
комиссионных Агентству недвижимости. Если вы встали на чужой участок, его владелец сразу получает право на одну сделку.</li>
<li><b>Деловой случай</b> — карта с доходом или убытком. Каждое страховое свидетельство (${fmt(CONST.INSURANCE_PRICE)}, не больше ${CONST.INSURANCE_MAX}) покрывает до ${fmt(CONST.INSURANCE_COVER)} убытка.</li>
<li><b>Консультация</b> — оплатите указанную сумму акционерам Консалтинговой компании.</li>
<li><b>Антимонопольный комитет</b> — владелец 2 или 3 акций одной компании обязан продать на аукционе 1 или 2 из них.</li>
<li><b>Дивиденды</b> — при проходе или остановке ${fmt(CONST.DIVIDEND)} за каждую акцию.</li>
<li><b>Доход от предприятий</b> — при проходе или остановке ${fmt(CONST.ENTERPRISE_INCOME)} за каждое введённое предприятие.</li>
<li><b>Налоговая инспекция</b> — налог 10% от номинала ваших акций и участков.</li>
<li><b>Банк</b> — при каждом проходе платите проценты по своим кредитам акционерам банка.</li>
</ul>

<h3>Акционерные компании</h3>
<p>У каждой компании 3 акции. Доход компании делится поровну между выкупленными акциями; если акционеров нет — доход уходит в банк.
При покупке любой акции 20% её цены получают акционеры Фондовой биржи. Продажа акции или участка — всегда через аукцион
(старт — номинал): продавцу 80%, 20% — бирже или агентству недвижимости. Если никто не купит, банк выкупает по номиналу.</p>
<ul>${co}</ul>
<p>Бизнес-школа и Консалтинговая компания берут с не-акционеров плату ${fmt(CONST.SCHOOL_FEE)} и ${fmt(CONST.RESEARCH_FEE)} при остановке на их клетке.</p>

<h3>Кредиты и векселя</h3>
<p>Кредит — ${fmt(CONST.CREDIT_AMOUNT)} под процент одной из свободных карт кредита (5–20%). Если вы не контролируете банк, процент назначают его акционеры
(берётся наибольший из названных). Погашается сумма кредита плюс процент. Остановившись на клетке «Банк», можно взять кредит под наименьший процент.</p>
<p>Займы между игроками — под вексель: сумма, процент и срок (в кругах) по договорённости. По истечении срока заимодавец может потребовать возврат.</p>

<h3>Финансовая необеспеченность и банкротство</h3>
<p>Если на обязательный платёж не хватает денег, нужно продать акции/участки или взять заём у игрока. Банковский кредит в этот момент не выдаётся.
Если денег всё равно не хватает — банкротство: имущество возвращается в банк, игрок выбывает.</p>

<h3>Конец игры</h3>
<p>Игрок, первым введший нужное число предприятий, получает премию ${fmt(CONST.FINISH_BONUS)}. Страховой фонд делится между акционерами
Страховой компании. Все гасят кредиты и векселя (при нехватке денег имущество сдаётся банку по номиналу), затем подсчитывается капитал.</p>`;
}
